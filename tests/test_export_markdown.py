"""Exporter framework (#014) and Markdown profile/timeline (#015) tests."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any

import pytest
from typer.testing import CliRunner

from experienceos.cli.app import app
from experienceos.exporters import default_exporter_registry
from experienceos.exporters.markdown import MarkdownExporter
from experienceos.storage import ExperienceStore

runner = CliRunner()


def full(result: Any) -> str:
    return result.output + (result.stderr or "")


@pytest.fixture
def two_records(cli_env, make_experience) -> tuple[str, str]:
    store = ExperienceStore(cli_env)
    active = make_experience(
        title="Campus Search",
        type="course_project",
        period={"start": "2023-01", "end": "2023-06"},
        role="engine lead",
        technology=["Python", "Whoosh"],
        contribution=["designed the inverted index"],
        result=["top-10 hit rate 92% in the demo"],
        evidence=[{"kind": "url", "location": "https://example.com/demo"}],
    )
    draft = make_experience(
        title="Secret Draft", period={"start": "2024-01", "end": None}, status="draft"
    )
    store.save(active)
    store.save(draft)
    return active.id, draft.id


class TestFramework:
    def test_markdown_registered_and_protocol_conformant(self) -> None:
        exporter = default_exporter_registry.get("markdown")
        assert exporter.name == "markdown"
        assert isinstance(exporter, MarkdownExporter)

    def test_unknown_exporter_lists_available(self, cli_env) -> None:
        result = runner.invoke(app, ["export", "nope"])
        output = full(result)
        assert result.exit_code == 1, output
        assert "unknown exporter 'nope'" in output
        assert "markdown" in output

    def test_list_flag(self, cli_env) -> None:
        result = runner.invoke(app, ["export", "--list"])
        assert result.exit_code == 0
        assert "markdown" in result.output

    def test_empty_selection_is_clean_exit(self, cli_env) -> None:
        result = runner.invoke(app, ["export", "markdown", "--out", "x.md"])
        assert result.exit_code == 0
        assert "No experiences match" in result.output


class TestMarkdownExport:
    def test_exports_active_records_only(
        self, cli_env, two_records, tmp_path: Path
    ) -> None:
        _active_id, _draft_id = two_records
        out = tmp_path / "profile.md"
        result = runner.invoke(app, ["export", "markdown", "--out", str(out)])
        assert result.exit_code == 0, full(result)
        assert f"-> {out}" in result.output
        content = out.read_text(encoding="utf-8")
        assert "Campus Search" in content
        assert "Secret Draft" not in content  # drafts never leak by default
        assert "- **Contribution**:" in content
        assert "  - designed the inverted index" in content
        assert "[url] https://example.com/demo" in content
        assert "record(s)" in content and "Generated by ExperienceOS" in content

    def test_status_filter_can_include_drafts(
        self, cli_env, two_records, tmp_path: Path
    ) -> None:
        _active_id, _draft_id = two_records
        out = tmp_path / "all.md"
        result = runner.invoke(
            app,
            ["export", "markdown", "--out", str(out), "--status", "draft"],
        )
        assert result.exit_code == 0, full(result)
        assert "Secret Draft" in out.read_text(encoding="utf-8")

    def test_type_filter_uses_search_query(
        self, cli_env, two_records, tmp_path: Path
    ) -> None:
        _active_id, _draft_id = two_records
        out = tmp_path / "filtered.md"
        result = runner.invoke(
            app, ["export", "markdown", "--out", str(out), "--type", "work"]
        )
        assert result.exit_code == 0
        assert "No experiences match" in result.output

    def test_timeline_groups_by_year(
        self, cli_env, two_records, tmp_path: Path
    ) -> None:
        out = tmp_path / "timeline.md"
        result = runner.invoke(
            app, ["export", "markdown", "--out", str(out), "--timeline"]
        )
        assert result.exit_code == 0, full(result)
        content = out.read_text(encoding="utf-8")
        # only the active record is exported by default: no 2024 section
        assert "## 2023" in content
        assert "## 2024" not in content
        assert "| Title | Type | Period |" in content
        assert "2023-01 ~ 2023-06" in content

    def test_empty_selection_rejected_at_exporter_level(self, tmp_path: Path) -> None:
        from experienceos.core.errors import ExportError

        with pytest.raises(ExportError, match="nothing to export"):
            MarkdownExporter().export([], tmp_path / "x.md")


