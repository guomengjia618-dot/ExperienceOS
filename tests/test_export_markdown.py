class TestDefaultNaming:
    def test_default_target_in_cwd(
        self, cli_env, two_records, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.chdir(tmp_path)
        import importlib

        # patch via importlib: plain attribute chains resolve to the
        # Typer `app` instance because cli/__init__ re-exports `app`
        module = importlib.import_module("experienceos.cli.app")
        monkeypatch.setattr(module, "datetime", _FrozenDatetime)
        result = runner.invoke(app, ["export", "markdown"])
        assert result.exit_code == 0, full(result)
        expected = tmp_path / "experienceos-export-markdown-20260829-120000.md"
        assert expected.exists()
        assert str(expected) in result.output


class _FrozenDatetime(datetime):
    @classmethod
    def now(cls, *args: Any, **kwargs: Any) -> datetime:
        return cls(2026, 8, 29, 12, 0, 0)
